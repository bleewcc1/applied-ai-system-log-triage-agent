"""
generate_eval_report.py

Test harness / evaluation script: runs triage_agent.process_log() against
a fixed set of sample logs with known expected outcomes, prints a
pass/fail summary with confidence ratings to stdout, and writes the same
results as a Markdown table into README.md.

Usage:
    python generate_eval_report.py
"""

from datetime import datetime, timezone
from pathlib import Path

from triage_agent import process_log

PROJECT_DIR = Path(__file__).parent
README_PATH = PROJECT_DIR / "README.md"

START_MARKER = "<!-- AUTO-GENERATED EVAL REPORT START -->"
END_MARKER = "<!-- AUTO-GENERATED EVAL REPORT END -->"

# process_log() raises ValueError for content it refuses to classify (the
# safe fallback), so "no severity" is itself an expected, testable outcome.
SAFE_FALLBACK = "ERROR (safe fallback)"

TEST_CASES = [
    ("logs/snort_alert_clean.log", "critical"),
    ("logs/netdata_anomaly_clean.json", "critical"),
    ("logs/snort_alert_high.log", "high"),
    ("logs/netdata_notice_low.json", "low"),
    ("logs/generic_app_log.txt", "low"),
    ("logs/corrupted_log.txt", SAFE_FALLBACK),
]


def run_case(relative_path: str) -> tuple[str, float | None]:
    """Run process_log on one sample log. Returns (severity, confidence_score)."""
    content = (PROJECT_DIR / relative_path).read_bytes().decode("utf-8", errors="replace")
    try:
        result = process_log(content)
        return result["severity"], result["confidence_score"]
    except ValueError:
        return SAFE_FALLBACK, None


def evaluate() -> list[dict]:
    rows = []
    for relative_path, expected in TEST_CASES:
        actual, confidence = run_case(relative_path)
        rows.append(
            {
                "input": relative_path,
                "expected": expected,
                "actual": actual,
                "confidence": confidence,
                "passed": actual == expected,
            }
        )
    return rows


def print_summary(rows: list[dict]) -> None:
    passed = sum(1 for r in rows if r["passed"])
    total = len(rows)
    confidences = [r["confidence"] for r in rows if r["confidence"] is not None]
    avg_confidence = sum(confidences) / len(confidences) if confidences else 0.0

    print(f"{passed} out of {total} test cases passed.")
    print(f"Average confidence score (successful classifications only): {avg_confidence:.2f}")
    print()
    for r in rows:
        mark = "PASS" if r["passed"] else "FAIL"
        conf = f"{r['confidence']:.2f}" if r["confidence"] is not None else "n/a"
        print(f"  [{mark}] {r['input']:<35} expected={r['expected']:<22} actual={r['actual']:<22} confidence={conf}")


def build_table(rows: list[dict]) -> str:
    lines = [
        "| Test Input | Expected Severity | Actual Severity | Confidence | Pass/Fail |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        conf = f"{r['confidence']:.2f}" if r["confidence"] is not None else "n/a"
        verdict = "✅ Pass" if r["passed"] else "❌ Fail"
        lines.append(f"| `{r['input']}` | {r['expected']} | {r['actual']} | {conf} | {verdict} |")
    return "\n".join(lines)


def build_section(rows: list[dict]) -> str:
    passed = sum(1 for r in rows if r["passed"])
    total = len(rows)
    confidences = [r["confidence"] for r in rows if r["confidence"] is not None]
    avg_confidence = sum(confidences) / len(confidences) if confidences else 0.0
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    return (
        f"{START_MARKER}\n"
        f"## Automated Evaluation Report\n\n"
        f"_Generated by `generate_eval_report.py` on {generated_at}._\n\n"
        f"{passed} out of {total} test cases passed. Average confidence score "
        f"(successful classifications only): {avg_confidence:.2f}.\n\n"
        f"{build_table(rows)}\n"
        f"{END_MARKER}\n"
    )


def update_readme(rows: list[dict]) -> None:
    section = build_section(rows)
    text = README_PATH.read_text(encoding="utf-8") if README_PATH.exists() else ""

    start = text.find(START_MARKER)
    end = text.find(END_MARKER)
    if start != -1 and end != -1 and end > start:
        end += len(END_MARKER)
        new_text = text[:start] + section.rstrip("\n") + "\n" + text[end:]
    elif text:
        new_text = text.rstrip("\n") + "\n\n" + section
    else:
        new_text = section

    README_PATH.write_text(new_text, encoding="utf-8")


def main() -> None:
    rows = evaluate()
    print_summary(rows)
    update_readme(rows)
    print()
    print(f"README.md updated with the Automated Evaluation Report section.")


if __name__ == "__main__":
    main()
